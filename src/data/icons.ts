/**
 * Given an icon, background options, and color options, generates a complete standalone SVG string.
 */
export function buildIconSvgMarkup(
  icon: IconDefinition,
  colorMode: IconColorMode = 'original',
  monochromeColor = '#000000',
  bgType: LogoBackgroundType = 'none',
  bgColor = '#ffffff',
  bgShape: LogoBackgroundShape = 'circle'
): string {
  const size = 120;
  const padding = bgType === 'none' ? 0 : 18;
  const innerSize = size - padding * 2;

  let bgPlate = '';
  if (bgType !== 'none') {
    const fill = bgType === 'white' ? '#ffffff' : bgColor;
    if (bgShape === 'circle') {
      bgPlate = `<circle cx="${size / 2}" cy="${size / 2}" r="${size / 2}" fill="${fill}" />`;
    } else if (bgShape === 'rounded') {
      bgPlate = `<rect width="${size}" height="${size}" rx="24" ry="24" fill="${fill}" />`;
    } else {
      bgPlate = `<rect width="${size}" height="${size}" rx="4" ry="4" fill="${fill}" />`;
    }
  }

  const content =
    colorMode === 'original'
      ? icon.originalSvg
      : `<g style="color: ${monochromeColor}">${icon.monochromePaths}</g>`;

  return `
    <svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
      ${bgPlate}
      <svg x="${padding}" y="${padding}" width="${innerSize}" height="${innerSize}" viewBox="${icon.viewBox}">
        ${content}
      </svg>
    </svg>
  `.trim();
}

/**
 * Returns a Data URL for the icon SVG
 */
export function getIconSvgDataUrl(
  icon: IconDefinition,
  colorMode: IconColorMode = 'original',
  monochromeColor = '#000000',
  bgType: LogoBackgroundType = 'none',
  bgColor = '#ffffff',
  bgShape: LogoBackgroundShape = 'circle'
): string {
  const svg = buildIconSvgMarkup(
    icon,
    colorMode,
    monochromeColor,
    bgType,
    bgColor,
    bgShape
  );
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

/**
 * Detect suggested icon by hostname matching
 */
export function getSuggestedIcon(urlStr: string): IconDefinition | null {
  try {
    const url = new URL(urlStr.startsWith('http') ? urlStr : `https://${urlStr}`);
    const host = url.hostname.toLowerCase();
    for (const icon of ICON_LIBRARY) {
      if (icon.matchDomains) {
        for (const dom of icon.matchDomains) {
          if (host === dom || host.endsWith(`.${dom}`)) {
            return icon;
          }
        }
      }
    }
  } catch {
    // Ignore invalid url during typing
  }
  return null;
}
